def classify(event):
    """给事件打类别标签（title + name + snippet 文本打分）。"""
    text = event.get("name", "")
    for rec in event.get("records", [])[:10]:
        text += " " + rec.get("title", "") + " " + (rec.get("snippet") or "")[:80]
    scores = {}
    for cat, kws in CATEGORIES.items():
        s = sum(text.count(k) for k in kws)
        if s:
            scores[cat] = s
    if not scores:
        return "其他"
    return max(scores.items(), key=lambda x: x[1])[0]
